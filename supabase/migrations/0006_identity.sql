-- 0006_identity: user accounts, role model, devices, persons; policy helpers; access-token hook.
-- Design: docs/design/erd.md §3 (identity.*) and §4 (visibility). Step 1.2.

-- ── Tables ──────────────────────────────────────────────────────────────────────────────────────

create table if not exists identity.user_account (
  id uuid primary key references auth.users (id) on delete restrict, -- = auth.users.id (server-generated)
  status text not null default 'active' check (status in ('active', 'suspended', 'closed')),
  preferred_locale text not null default 'fr' check (preferred_locale in ('fr', 'en')),
  suspended_reason text check (char_length(suspended_reason) <= 500),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  created_by uuid references identity.user_account (id),
  client_created_at timestamptz,
  row_version integer not null default 1
);
comment on table identity.user_account is 'Application profile of each Supabase Auth user (erd.md). Not synced to devices.';

create table if not exists identity.membership (
  id uuid primary key default gen_random_uuid(),
  user_account_id uuid not null references identity.user_account (id),
  role text not null check (role in (
    'patient', 'caregiver', 'clinician', 'facility_admin', 'chw', 'chw_supervisor',
    'lab_staff', 'pharmacy_staff', 'platform_support', 'platform_admin')),
  organization_id uuid, -- FK to provider.organization added in 0007
  valid_from timestamptz not null default now(),
  valid_to timestamptz,
  status text not null default 'active' check (status in ('active', 'suspended', 'ended')),
  granted_by uuid references identity.user_account (id),
  end_reason text check (char_length(end_reason) <= 500),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  created_by uuid references identity.user_account (id),
  client_created_at timestamptz,
  row_version integer not null default 1,
  constraint membership_org_scope check (
    (role in ('patient', 'caregiver', 'platform_support', 'platform_admin')) = (organization_id is null)),
  constraint membership_validity check (valid_to is null or valid_to >= valid_from)
);
comment on table identity.membership is 'Role model: who holds which role, in which organization, for which period (Step 1.2).';
create index if not exists membership_user_idx on identity.membership (user_account_id) where status = 'active';
create index if not exists membership_org_idx on identity.membership (organization_id) where status = 'active';

create table if not exists identity.device_registration (
  id uuid primary key, -- generated by the app on first launch
  user_account_id uuid not null references identity.user_account (id),
  app text not null check (app in ('patient', 'chw', 'web')),
  platform text not null check (platform in ('android', 'ios', 'web')),
  app_version text check (char_length(app_version) <= 50),
  public_key text check (char_length(public_key) <= 1000),
  trust_status text not null default 'active' check (trust_status in ('active', 'revoked')),
  last_sync_at timestamptz,
  revoked_at timestamptz,
  revoked_by uuid references identity.user_account (id),
  revocation_reason text check (char_length(revocation_reason) <= 500),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  created_by uuid references identity.user_account (id),
  client_created_at timestamptz,
  row_version integer not null default 1,
  constraint device_revocation_consistent check ((trust_status = 'revoked') = (revoked_at is not null))
);
comment on table identity.device_registration is 'One row per app install per user; unit of revocation and remote purge (OFF-007).';
create index if not exists device_user_idx on identity.device_registration (user_account_id);

create table if not exists identity.person (
  id uuid primary key default gen_random_uuid(), -- client-generated when created offline
  user_account_id uuid unique references identity.user_account (id),
  family_name text not null check (char_length(family_name) between 1 and 100),
  given_names text not null check (char_length(given_names) between 1 and 150),
  other_names text check (char_length(other_names) <= 150),
  birth_date date check (birth_date > date '1900-01-01'),
  birth_date_precision text not null default 'exact'
    check (birth_date_precision in ('exact', 'year_month', 'year', 'estimated', 'unknown')),
  sex text not null default 'unknown' check (sex in ('female', 'male', 'other', 'unknown')),
  phone text check (phone ~ '^\+[1-9][0-9]{6,14}$'),
  email text check (char_length(email) <= 254 and email like '%@%'),
  preferred_language text check (char_length(preferred_language) <= 16), -- BCP-47 tag
  village_or_quarter text check (char_length(village_or_quarter) <= 150),
  district text check (char_length(district) <= 100),
  region text check (char_length(region) <= 100),
  status text not null default 'active' check (status in ('active', 'inactive', 'entered_in_error')),
  origin_device_id uuid references identity.device_registration (id),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  created_by uuid references identity.user_account (id),
  client_created_at timestamptz,
  row_version integer not null default 1
);
comment on table identity.person is 'One human: demographics and contact, shared by patient, practitioner and related_person (erd.md).';

