  identity.person to service_role;

-- ── Policies ────────────────────────────────────────────────────────────────────────────────────

drop policy if exists user_account_select on identity.user_account;
create policy user_account_select on identity.user_account
  for select to authenticated
  using (
    id = (select auth.uid())
    or ((select identity.has_role('platform_admin')) and (select identity.aal2()))
  );

drop policy if exists membership_select on identity.membership;
create policy membership_select on identity.membership
  for select to authenticated
  using (
    user_account_id = (select auth.uid())
    or ((select identity.aal2()) and (
      (select identity.has_role('platform_admin'))
      or (organization_id is not null and identity.has_role('facility_admin', organization_id))
    ))
  );

drop policy if exists device_select on identity.device_registration;
create policy device_select on identity.device_registration
  for select to authenticated
  using (
    user_account_id = (select auth.uid())
    or ((select identity.aal2()) and (
      (select identity.has_role('platform_admin')) or (select identity.has_role('platform_support'))
    ))
  );
