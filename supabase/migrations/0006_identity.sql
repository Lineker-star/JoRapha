-- ── Policy helpers (SECURITY DEFINER: they read the role tables regardless of the caller's RLS) ──

create or replace function identity.aal2()
returns boolean
language sql
stable
set search_path = ''
as $$
  select coalesce((select auth.jwt() ->> 'aal') = 'aal2', false);
$$;
comment on function identity.aal2() is 'True when the session completed MFA (assurance level aal2).';

create or replace function identity.has_role(p_role text, p_organization_id uuid default null)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from identity.membership as m
    join identity.user_account as u on u.id = m.user_account_id
    where m.user_account_id = auth.uid()
      and u.status = 'active'
      and m.role = p_role
      and m.status = 'active'
      and m.valid_from <= now()
      and (m.valid_to is null or m.valid_to > now())
      and (p_organization_id is null or m.organization_id = p_organization_id)
  );
$$;
comment on function identity.has_role(text, uuid) is
  'Active membership of the caller in a role (optionally in one organization). Reads the tables, not the JWT, so revocation is immediate.';

create or replace function identity.in_org(p_organization_id uuid)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from identity.membership as m
    join identity.user_account as u on u.id = m.user_account_id
    where m.user_account_id = auth.uid()
      and u.status = 'active'
      and m.organization_id = p_organization_id
      and m.status = 'active'
      and m.valid_from <= now()
      and (m.valid_to is null or m.valid_to > now())
  );
$$;
comment on function identity.in_org(uuid) is 'Caller holds any active role in the organization.';

create or replace function identity.current_person_id()
returns uuid
language sql
stable
security definer
set search_path = ''
as $$
  select p.id from identity.person as p where p.user_account_id = auth.uid();
$$;

revoke execute on function identity.aal2(), identity.has_role(text, uuid), identity.in_org(uuid),
  identity.current_person_id() from public, anon;
grant execute on function identity.aal2(), identity.has_role(text, uuid), identity.in_org(uuid),
  identity.current_person_id() to authenticated, service_role;

-- ── Account creation: every auth user gets an identity.user_account row ─────────────────────────

create or replace function private.handle_new_auth_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into identity.user_account (id) values (new.id) on conflict (id) do nothing;
  return new;
end;
$$;

create or replace trigger on_auth_user_created
  after insert on auth.users
  for each row execute function private.handle_new_auth_user();

insert into identity.user_account (id) select id from auth.users on conflict (id) do nothing;

-- ── Custom access-token hook: active roles and organization ids in the JWT (for the UI) ─────────
-- Policies do NOT trust these claims (they call identity.has_role), so a revoked role stops working
-- immediately, not at token expiry.

create or replace function identity.custom_access_token_hook(event jsonb)
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v_claims jsonb := coalesce(event -> 'claims', '{}'::jsonb);
  v_roles jsonb;
  v_orgs jsonb;
begin
  select
    coalesce(jsonb_agg(distinct m.role), '[]'::jsonb),
    coalesce(jsonb_agg(distinct m.organization_id) filter (where m.organization_id is not null), '[]'::jsonb)
  into v_roles, v_orgs
  from identity.membership as m
  join identity.user_account as u on u.id = m.user_account_id
  where m.user_account_id = (event ->> 'user_id')::uuid
    and u.status = 'active'
    and m.status = 'active'
    and m.valid_from <= now()
    and (m.valid_to is null or m.valid_to > now());

  v_claims := jsonb_set(v_claims, '{app_roles}', v_roles);
  v_claims := jsonb_set(v_claims, '{app_org_ids}', v_orgs);
  return jsonb_set(event, '{claims}', v_claims);
end;
$$;
revoke execute on function identity.custom_access_token_hook(jsonb) from public, anon, authenticated;
grant usage on schema identity to supabase_auth_admin;
grant execute on function identity.custom_access_token_hook(jsonb) to supabase_auth_admin;

-- ── Privileges: reads through RLS; no client writes (writes go through api.*) ──────────────────

revoke all on identity.user_account, identity.membership, identity.device_registration, identity.person
  from public, anon, authenticated;
