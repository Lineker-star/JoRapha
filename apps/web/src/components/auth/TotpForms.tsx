'use client';

import type { Locale } from '@jorapha/i18n';
import { useTranslations } from 'next-intl';
import { useActionState } from 'react';

import { type EnrollState, startTotpEnrollment, verifyTotp } from '@/lib/auth/actions';

import { Field, FormMessage, SubmitButton } from './FormParts';

const empty: EnrollState = {};

function VerifyForm({
  locale,
  next,
  factorId,
  initial,
}: {
  locale: Locale;
  next: string;
  factorId: string;
  initial: EnrollState;
}) {
  const t = useTranslations('auth');
  const [state, action] = useActionState(verifyTotp, initial);
  return (
    <form action={action} className="space-y-4">
      <input type="hidden" name="locale" value={locale} />
      <input type="hidden" name="next" value={next} />
      <input type="hidden" name="factorId" value={factorId} />
      <Field
        label={t('mfa.code')}
        name="code"
        inputMode="numeric"
        autoComplete="one-time-code"
        pattern="\d{6}"
        maxLength={6}
        required
      />
      {state.error ? <FormMessage tone="error">{t(`errors.${state.error}`)}</FormMessage> : null}
      <SubmitButton>{t('mfa.verify')}</SubmitButton>
    </form>
  );
}

/** First-time set-up: QR code (an SVG data URI generated by Supabase Auth) or the key, then a first code. */
export function TotpEnroll({ locale, next }: { locale: Locale; next: string }) {
  const t = useTranslations('auth');
  const [enrolment, start] = useActionState(startTotpEnrollment, empty);
  if (!enrolment.factorId || !enrolment.qrCode) {
    return (
      <form action={start} className="space-y-4">
        <p className="text-ink-600">{t('mfa.enrollIntro')}</p>
        {enrolment.error ? (
          <FormMessage tone="error">{t(`errors.${enrolment.error}`)}</FormMessage>
        ) : null}
        <SubmitButton>{t('mfa.start')}</SubmitButton>
      </form>
    );
  }
  return (
    <div className="space-y-4">
      <p className="text-ink-600">{t('mfa.scanQr')}</p>
      {/* A data: URI from Supabase Auth; next/image does not apply to inline SVG data. */}
      {/* eslint-disable-next-line @next/next/no-img-element */}
      <img
        src={enrolment.qrCode}
        alt={t('mfa.qrAlt')}
        width={200}
        height={200}
        className="rounded-lg border border-slate-200 bg-white p-2"
      />
      <p className="text-sm text-ink-600">
        {t('mfa.secretLabel')}{' '}
        <code className="break-all rounded bg-surface-muted px-1 font-mono">
          {enrolment.secret}
        </code>
      </p>
      <VerifyForm locale={locale} next={next} factorId={enrolment.factorId} initial={{}} />
    </div>
  );
}

/** Later sign-ins: a code from the already enrolled authenticator. */
export function TotpChallenge({
  locale,
  next,
  factorId,
}: {
  locale: Locale;
  next: string;
  factorId: string;
}) {
  const t = useTranslations('auth');
  return (
    <div className="space-y-4">
      <p className="text-ink-600">{t('mfa.challengeIntro')}</p>
      <VerifyForm locale={locale} next={next} factorId={factorId} initial={{}} />
    </div>
  );
}
